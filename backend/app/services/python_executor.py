"""
Safe Python Math & Formula Execution Sandbox.
Executes deterministic mathematical and scientific calculations generated by the LLM
without risking arbitrary code execution or filesystem/network access.
"""

import ast
import math
import sys
from typing import Dict, Any, Tuple, Optional

# Safe builtins and math constants/functions
SAFE_BUILTINS = {
    "abs": abs,
    "round": round,
    "min": min,
    "max": max,
    "sum": sum,
    "len": len,
    "float": float,
    "int": int,
    "str": str,
    "bool": bool,
    "range": range,
    "enumerate": enumerate,
    "zip": zip,
    "dict": dict,
    "list": list,
    "set": set,
    "print": None,  # Will be overridden with our capture function
}

# Add math module utilities
for attr in dir(math):
    if not attr.startswith("_"):
        SAFE_BUILTINS[attr] = getattr(math, attr)

# Common unit conversion constants
SAFE_BUILTINS["M3_TO_CUFT"] = 35.3146667
SAFE_BUILTINS["CUFT_TO_M3"] = 1.0 / 35.3146667
SAFE_BUILTINS["MM_TO_M"] = 0.001
SAFE_BUILTINS["M_TO_MM"] = 1000.0
SAFE_BUILTINS["PSI_TO_KPA"] = 6.89476
SAFE_BUILTINS["KPA_TO_PSI"] = 0.145038


class SecurityVisitor(ast.NodeVisitor):
    """
    AST visitor that rejects dangerous constructs like imports,
    dunder attributes, system calls, file operations, etc.
    """
    DISALLOWED_NODES = (
        ast.Import,
        ast.ImportFrom,
        ast.Global,
        ast.Nonlocal,
        ast.AsyncFunctionDef,
        ast.AsyncFor,
        ast.AsyncWith,
    )

    def visit(self, node: ast.AST):
        if isinstance(node, self.DISALLOWED_NODES):
            raise ValueError(f"Disallowed Python construct: {type(node).__name__}")
        
        # Check attribute access for dunder like __subclasses__, __globals__, etc.
        if isinstance(node, ast.Attribute):
            if node.attr.startswith("__"):
                raise ValueError(f"Access to private attribute '{node.attr}' is not permitted.")
                
        # Check function calls for disallowed names
        if isinstance(node, ast.Call):
            if isinstance(node.func, ast.Name):
                if node.func.id in ("eval", "exec", "open", "compile", "__import__", "getattr", "setattr", "delattr"):
                    raise ValueError(f"Function '{node.func.id}' is prohibited in calculation sandbox.")
                    
        self.generic_visit(node)


def execute_safe_python(code_snippet: str, timeout_seconds: float = 2.0) -> Tuple[bool, str, Dict[str, Any]]:
    """
    Executes a Python code snippet in a heavily sandboxed environment.
    
    Returns:
        (success: bool, output_logs: str, variables: Dict[str, Any])
    """
    # 1. Parse AST and validate security
    try:
        tree = ast.parse(code_snippet)
        validator = SecurityVisitor()
        validator.visit(tree)
    except SyntaxError as se:
        return False, f"Syntax Error: {str(se)}", {}
    except ValueError as ve:
        return False, f"Security Violation: {str(ve)}", {}
    except Exception as e:
        return False, f"Validation Error: {str(e)}", {}

    # 2. Setup captured output
    output_lines = []

    def custom_print(*args, **kwargs):
        sep = kwargs.get("sep", " ")
        text = sep.join(str(a) for a in args)
        output_lines.append(text)

    sandbox_scope = dict(SAFE_BUILTINS)
    sandbox_scope["print"] = custom_print

    # 3. Execute compiled AST
    try:
        compiled = compile(tree, filename="<sandbox_calculation>", mode="exec")
        local_scope: Dict[str, Any] = {}
        exec(compiled, {"__builtins__": sandbox_scope}, local_scope)

        # Filter out non-serializable variables for return
        clean_vars = {}
        for k, v in local_scope.items():
            if not k.startswith("_") and isinstance(v, (int, float, str, bool, list, dict, tuple)):
                clean_vars[k] = v

        output_str = "\n".join(output_lines)
        if not output_str and clean_vars:
            # Auto-format results if print wasn't explicitly called
            output_str = ", ".join(f"{k} = {v}" for k, v in clean_vars.items())

        return True, output_str, clean_vars
    except Exception as e:
        return False, f"Runtime Execution Error: {type(e).__name__}: {str(e)}", {}


def extract_and_run_code_blocks(text_content: str) -> Optional[Tuple[str, str, Dict[str, Any]]]:
    """
    Finds Python code blocks (```python ... ```) inside LLM output,
    executes them, and returns (raw_code, logs, variables).
    """
    import re
    code_blocks = re.findall(r"```(?:python|py)?\s*(.*?)\s*```", text_content, re.DOTALL)
    if not code_blocks:
        return None

    all_logs = []
    combined_vars = {}
    last_code = ""

    for block in code_blocks:
        last_code = block.strip()
        success, logs, vars_dict = execute_safe_python(last_code)
        if logs:
            all_logs.append(logs)
        combined_vars.update(vars_dict)

    return last_code, "\n".join(all_logs), combined_vars
